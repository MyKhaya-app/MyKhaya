#!/usr/bin/env python3
"""Docker Secrets: provision, verify and scan (MK-SEC-001 v1.2).

Run by the Owner, as root, through dev-secrets-cutover.sh or, with
``--environment prod``, prod-security-migrate.sh. Never prints, hashes
or logs a value: results name variables, files and containers only.

    provision  build <root>/file-backed from the active F-03 files. Every secret
               is the existing value; nothing is generated or rotated. Refuses
               to overwrite anything, and writes everything or nothing.
    verify     prove every provisioned file still equals the F-03 value.
    scan       look for any provisioned secret in the containers' Docker
               metadata, logs and process arguments (PROD: also stopped ones).
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import service_env_contract as contract  # noqa: E402

PROJECT = "mykhaya"
# Short values (for example a username-like client ID) would match by chance.
MINIMUM_SCAN_LENGTH = 8


class MigrationError(Exception):
    """The message is safe to print."""


# Set once by main(): the F-03 profile of the environment being migrated.
SOURCE = contract.DEV


def load_source(root: Path, repo_root: Path) -> dict[str, dict[str, str]]:
    """The validated F-03 files (dev-deploy.sh has already checked modes)."""
    report = contract.validate_root(root, repo_root=repo_root, check_perms=False, profile=SOURCE)
    if report.errors:
        raise MigrationError("the F-03 configuration is not valid:\n- "
                             + "\n- ".join(report.errors))
    return {c.name: contract.parse_env_file(root / c.name)[0] for c in SOURCE.contracts}


def derive(root: Path, repo_root: Path) -> tuple[dict[str, dict[str, str]], dict[str, str]]:
    files, values, problems = contract.derive_file_backed(load_source(root, repo_root), SOURCE)
    if problems:
        raise MigrationError("the credentials cannot be moved unchanged:\n- "
                             + "\n- ".join(problems))
    return files, values


def stored_bytes(value: str) -> bytes:
    """One trailing newline, which every reader removes; empty stays empty."""
    return (value + "\n").encode("utf-8") if value else b""


def _write(path: Path, data: bytes, uid: int, gid: int, mode: int) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600)
    with os.fdopen(fd, "wb") as handle:
        handle.write(data)
        handle.flush()
        os.fsync(handle.fileno())
    os.chown(path, uid, gid)
    os.chmod(path, mode)


def _directory(path: Path, uid: int, gid: int, mode: int) -> None:
    path.mkdir(mode=0o700)
    os.chown(path, uid, gid)
    os.chmod(path, mode)


def provision(root: Path, repo_root: Path) -> None:
    target = root / "file-backed"
    if target.exists() or target.is_symlink():
        raise MigrationError("file-backed already exists; it is never overwritten. Verify it, or "
                             "move it aside deliberately")
    if root.is_symlink():
        raise MigrationError("the configuration root must not be a symbolic link")
    files, values = derive(root, repo_root)
    owner = root.stat()
    staging = root / f".file-backed.staging-{os.getpid()}"
    old_umask = os.umask(0o077)
    try:
        # Not searchable by the deployment account until everything is in place.
        _directory(staging, 0, 0, 0o700)
        for item in contract.FILE_BACKED[SOURCE.name].contracts:
            lines = [f"# Generated by dev_secrets_migration.py. Contract: {item.name}.\n"]
            lines += [f"{name}={contract.format_env_value(files[item.name][name])}\n"
                      for name in sorted(files[item.name])]
            path = staging / item.name
            _write(path, "".join(lines).encode("utf-8"), owner.st_uid, owner.st_gid, 0o640)
            parsed, problems = contract.parse_env_file(path)
            if problems or parsed != files[item.name]:
                raise MigrationError(f"{item.name} did not round-trip exactly")
        _directory(staging / "secrets", 0, owner.st_gid, 0o750)
        for store, gid in (("app", contract.SERVICE_GID), ("postgres", contract.POSTGRES_GID)):
            _directory(staging / "secrets" / store, 0, gid, 0o750)
            for secret in contract.SECRET_FILE_SPECS:
                if secret.store != store:
                    continue
                path = staging / "secrets" / store / secret.name
                _write(path, stored_bytes(values[secret.name]), 0, gid, 0o440)
                if path.read_bytes() != stored_bytes(values[secret.name]):
                    raise MigrationError(f"{secret.name} did not round-trip exactly")
        os.chown(staging, owner.st_uid, owner.st_gid)
        os.chmod(staging, 0o750)
        os.rename(staging, target)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    finally:
        os.umask(old_umask)
    configured = sum(1 for v in values.values() if v)
    print(f"Provisioned {configured} secrets and {len(values) - configured} unconfigured "
          "placeholders (values not shown). The F-03 files are unchanged.")


def verify(root: Path, repo_root: Path) -> None:
    target = root / "file-backed"
    files, values = derive(root, repo_root)
    problems: list[str] = []
    for item in contract.FILE_BACKED[SOURCE.name].contracts:
        path = target / item.name
        if path.is_symlink() or not path.is_file():
            problems.append(f"{item.name}: is missing or not a regular file")
            continue
        parsed, errors = contract.parse_env_file(path)
        if errors or parsed != files[item.name]:
            problems.append(f"{item.name}: differs from the F-03 configuration")
    for secret in contract.SECRET_FILE_SPECS:
        path = target / "secrets" / secret.store / secret.name
        try:
            info = path.lstat()
            if not stat.S_ISREG(info.st_mode):
                problems.append(f"{secret.name}: is not a regular file")
            elif path.read_bytes() != stored_bytes(values[secret.name]):
                problems.append(f"{secret.name}: differs from the F-03 credential")
        except OSError:
            problems.append(f"{secret.name}: is missing or unreadable")
    if problems:
        raise MigrationError("verification failed:\n- " + "\n- ".join(problems))
    print(f"Verified: {len(values)} secret files and {len(contract.FILE_BACKED[SOURCE.name].contracts)} "
          "environment files equal the F-03 configuration.")


def _docker(*arguments: str) -> bytes:
    result = subprocess.run(["docker", *arguments], capture_output=True, check=False)
    if result.returncode != 0:
        raise MigrationError(f"docker {arguments[0]} failed")
    return result.stdout + result.stderr


def secret_needles(target: Path) -> dict[str, list[bytes]]:
    needles: dict[str, list[bytes]] = {}
    for secret in contract.SECRET_FILE_SPECS:
        data = (target / "secrets" / secret.store / secret.name).read_bytes().rstrip(b"\n")
        if len(data) < MINIMUM_SCAN_LENGTH:
            continue
        if secret.kind == "pem":  # any full body line identifies the key
            lines = [l for l in data.split(b"\n") if not l.startswith(b"-----") and len(l) >= 32]
            needles[secret.name] = lines[:1]
        else:
            # Docker prints metadata as JSON, which escapes some characters.
            escaped = json.dumps(data.decode("utf-8"), ensure_ascii=False)[1:-1].encode()
            needles[secret.name] = sorted({data, escaped})
    return needles


def scan(root: Path) -> None:
    needles = secret_needles(root / "file-backed")
    stopped = ["-a"] if SOURCE is contract.PROD else []
    ids = _docker("ps", *stopped, "-q", "--no-trunc", "--filter",
                  f"label=com.docker.compose.project={PROJECT}").split()
    if not ids:
        raise MigrationError("no running containers were found")
    found: list[str] = []
    for raw in ids:
        container = raw.decode()
        service = _docker("inspect", "--format",
                          '{{index .Config.Labels "com.docker.compose.service"}}',
                          container).decode().strip()
        created = _docker("inspect", "--format", "{{.Created}}", container).decode().strip()
        running = _docker("inspect", "--format", "{{.State.Running}}", container).strip() == b"true"
        places = [("Docker metadata", _docker("inspect", container)),
                  ("logs", _docker("logs", "--since", created, container))]
        if running:
            places.append(("process arguments", _docker("top", container, "-eo", "pid,args")))
        for place, data in places:
            for name, patterns in needles.items():
                if any(p and p in data for p in patterns):
                    found.append(f"{service}: {name} appears in {place}")
    if found:
        raise MigrationError("secrets are exposed:\n- " + "\n- ".join(found))
    print(f"Scanned {len(ids)} containers for {len(needles)} secrets: none found in Docker "
          "metadata, process arguments or logs.")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("action", choices=("provision", "verify", "scan"))
    parser.add_argument("--root", type=Path, required=True, help="the F-03 configuration root")
    parser.add_argument("--environment", choices=sorted(contract.FILE_BACKED), default="dev")
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args(argv)
    global SOURCE
    SOURCE = contract.PROFILES[args.environment]
    if os.name != "posix" or os.geteuid() != 0:
        print(f"ERROR: this must run as root on the {SOURCE.label} host", file=sys.stderr)
        return 2
    try:
        if args.action == "scan":
            scan(args.root)
        else:
            {"provision": provision, "verify": verify}[args.action](args.root, args.repo_root)
    except MigrationError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    except OSError as exc:
        # The strerror only: an OSError's own text can carry a path.
        print(f"ERROR: {args.action} failed: {exc.strerror}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
